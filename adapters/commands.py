# 마커는 **렌더링에 보이지 않는 주석**이어야 한다.
# bin/jig 는 bash 주석(heredoc 밖), README 는 HTML 주석.
_TAG = "jig commands (generated by `jig docs --update`)"
TARGETS = {
    "bin/jig": (f"    # >>> {_TAG} >>>", "    # <<< jig commands <<<"),
    "README.md": (f"<!-- >>> {_TAG} >>> -->", "<!-- <<< jig commands <<< -->"),
    "README.ko.md": (f"<!-- >>> {_TAG} >>> -->", "<!-- <<< jig commands <<< -->"),
}


def _w(s: str) -> int:
    """터미널 표시 폭. 한글은 두 칸을 차지하므로 len() 으로는 정렬이 안 맞는다."""
    return sum(2 if unicodedata.east_asian_width(c) in "WF" else 1 for c in s)


def _pad(s: str, width: int) -> str:
    return s + " " * max(1, width - _w(s))


def _rows(ko: bool) -> list[tuple[str, str, str]]:
    out = []
    for group, inv_en, inv_ko, en, kodesc in COMMANDS:
        out.append((group, f"jig {inv_ko if ko else inv_en}", kodesc if ko else en))
    return out


def render_help() -> str:
    """bin/jig 의 heredoc 전체 (한국어)."""
    rows = _rows(ko=True)
    width = max(_w(inv) for _, inv, _ in rows) + 3
    lines = ["jig — 프로필 하네스 (jigkit)"]
    for group, _, header_ko in GROUPS:
        mine = [(i, d) for g, i, d in rows if g == group]
        if not mine:
            continue
        lines.append("")
        if header_ko:
            lines.append(header_ko)
        for inv, desc in mine:
            lines.append("  " + _pad(inv, width) + desc)
    return "\n".join(lines)


def render_md(ko: bool) -> str:
    """README 의 명령 블록 (```bash 펜스 포함)."""
    rows = _rows(ko)
    width = max(_w(inv) for _, inv, _ in rows) + 3
    lines = ["```bash"]
    for group, header_en, header_ko in GROUPS:
        mine = [(i, d) for g, i, d in rows if g == group]
        if not mine:
            continue
        header = header_ko if ko else header_en
        if header:
            lines.append("")
            lines.append(f"# {header}")
        for inv, desc in mine:
            lines.append(_pad(inv, width) + "# " + desc)
    lines.append("```")
    return "\n".join(lines)


def rendered(target: str) -> str:
    if target == "bin/jig":
        return "    cat <<'USAGE'\n" + render_help() + "\nUSAGE"
    return render_md(ko=target.endswith(".ko.md"))


def _splice(text: str, start: str, end: str, body: str) -> str:
    lines = text.splitlines()
    try:
        i = lines.index(start)
        j = lines.index(end)
    except ValueError:
        raise LookupError(f"마커를 찾지 못했다:\n  {start}\n  {end}")
    return "\n".join(lines[: i + 1] + body.splitlines() + lines[j:]) + "\n"


def apply(write: bool) -> list[str]:
    """마커 사이를 다시 쓴다. 바뀐(또는 바뀌어야 할) 파일 목록을 돌려준다."""
    stale = []
    for target, (start, end) in TARGETS.items():
        path = HARNESS / target
        old = path.read_text(encoding="utf-8")
        new = _splice(old, start, end, rendered(target))
        if new == old:
            continue
        stale.append(target)
        if write:
            path.write_text(new, encoding="utf-8")
            if path.read_text(encoding="utf-8") != new:  # P09
                raise OSError(f"{path} 를 썼지만 되읽은 내용이 다르다.")
    return stale
