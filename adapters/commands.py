#!/usr/bin/env python3
"""명령 정의의 단일 진실. 도움말과 README 명령 블록을 여기서 생성한다.

같은 사실이 네 곳(`cli.py` 디스패치 · `bin/jig` 도움말 · `README.md` ·
`README.ko.md`)에 살면 반드시 어긋난다. 가정이 아니다 — **최초 커밋부터**
`cli.py` 는 `build`·`budget`·`growth`·`golden` 을 받았는데 `bin/jig` 도움말은
한 번도 그것들을 실은 적이 없다. 그 뒤 도움말을 4번 고쳤는데도 안 맞춰졌다.

검사로 잡는 대신 **어긋날 곳을 없앤다.** 이 표에서 세 곳을 생성한다.

생성은 런타임이 아니라 **커밋되는 코드 생성**이다. `bin/jig` 의 도움말은 순수 bash 로
남아야 한다 — `new` 와 `help` 는 PyYAML 없이 동작하도록 일부러 bash 에서 처리하고,
bootstrap.sh 의 존재 이유가 "의존성이 없을 때도 안내가 나와야 한다" 이다. 런타임에
파이썬으로 만들면 PyYAML 이 없을 때 도움말 대신 트레이스백이 나온다.
"""
