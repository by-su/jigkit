#!/usr/bin/env python3
"""스택 카탈로그. 도구 중립 — Claude Code 문법을 모른다.

`library/stacks/*.yaml` 하나에서 **카탈로그 문서 · `jig stack` 출력 · 배치 절차**가 모두
나온다. 문서와 동작을 따로 쓰면 어긋나기 때문이다(`commands.py` 가 생긴 것과 같은 이유).

이 파일은 **아무것도 쓰지 않는다.** 파일을 쓰는 것은 `adapters/claude/stack_apply.py` 뿐이다 —
경계가 그렇게 그어져 있어서 `list`·`show`·`show --plan`·`check` 는 어디서 돌려도 안전하다.
"""
from __future__ import annotations

import json
import re
import shlex
import tomllib
from pathlib import Path

import yaml

HARNESS = Path(__file__).resolve().parents[1]
STACKS = HARNESS / "library" / "stacks"
MCP_DIR = HARNESS / "library" / "mcp"

# 카탈로그 표의 "기능별" 축. 여기 없는 role 은 로드가 거부한다 — 자유 문자열이면
# `lint`/`linting`/`format` 이 섞여 표가 조용히 갈라진다.
ROLES = [
    "runtime", "lint", "types", "test", "framework", "backend", "db", "ui",
    "e2e", "mobile", "observability", "security", "analytics", "design",
    "container", "perf",
]
SURFACES = ["mcp", "agents", "hook", "gate", "library"]

MARKERS = (
    "<!-- >>> jig stacks (generated by `jig docs --update`) >>> -->",
    "<!-- <<< jig stacks <<< -->",
)
CATALOG = STACKS / "README.md"

# 대상 프로젝트의 훅 디스패처 안에서 생성물 구간을 두르는 마커. 배치(stack_apply)와
# 대조(check)가 **같은 구간을 봐야** 한다 — 그래서 한 곳에 둔다.
HOOK_MARKERS = ("# >>> jig stack (generated by `jig stack apply`) >>>",
                "# <<< jig stack <<<")
ID_COMMENT = re.compile(r"#\s*([A-Za-z0-9_.@/-]+)\s*$")


class StackError(Exception):
    """정의가 어긋난 경우. 조용히 넘어가지 않는다."""


# ---------------------------------------------------------------- 로드와 검증

def _read(path: Path) -> dict:
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as e:
        raise StackError(f"{path.name} 파싱 실패: {e}") from e
    if not isinstance(data, dict):
        raise StackError(f"{path.name}: 최상위가 매핑이 아니다")
    return data


def _items_of(block: dict) -> list[dict]:
    items = block.get("items") or []
    if not isinstance(items, list):
        raise StackError("items 가 목록이 아니다")
    return items


def _validate_item(item: dict, where: str) -> None:
    for field in ("id", "role", "surface"):
        if not item.get(field):
            raise StackError(f"{where}: {field} 가 없다 — {item}")
    if item["role"] not in ROLES:
        raise StackError(f"{where}: 모르는 role {item['role']!r} (ROLES 에 추가해야 한다)")
    if item["surface"] not in SURFACES:
        raise StackError(f"{where}: 모르는 surface {item['surface']!r}")
    surface = item["surface"]
    if surface == "hook":
        hook = item.get("hook") or {}
        if not hook:
            raise StackError(f"{where}: surface: hook 인데 hook 정의가 없다 — {item['id']}")
        # 이벤트당 디스패처가 하나라는 전제 위에 배치가 서 있다. 다른 이벤트를 쓰려면
        # 디스패처를 하나 더 만들어야 하므로 조용히 받지 않는다.
        if hook.get("event", "PostToolUse") != "PostToolUse":
            raise StackError(f"{where}: hook.event 는 PostToolUse 만 지원한다 — {item['id']}")
        if not hook.get("ext") or not hook.get("run"):
            raise StackError(f"{where}: hook 에 ext·run 이 필요하다 — {item['id']}")
    if surface == "gate":
        gate = item.get("gate") or {}
        if not gate:
            raise StackError(f"{where}: surface: gate 인데 gate 정의가 없다 — {item['id']}")
        if not gate.get("run"):
            # 여기서 안 잡으면 apply 때 KeyError 트레이스백으로 나온다.
            raise StackError(f"{where}: gate 에 run 이 필요하다 — {item['id']}")
    if surface == "mcp":
        if not item.get("mcp"):
            raise StackError(f"{where}: surface: mcp 인데 mcp 정의가 없다 — {item['id']}")
        # MCP 정의는 `library/mcp/<id>.json` 으로 나간다. detect 가 다른 이름을 보면
        # 배치가 성공해도 check 가 영원히 "감지 실패" 를 낸다 (실제로 그랬다).
        named = (item.get("detect") or {}).get("mcp")
        if named and named != item["id"]:
            raise StackError(
                f"{where}: detect.mcp({named}) 가 id({item['id']}) 와 다르다 — "
                f"MCP 정의 파일 이름은 id 다"
            )
    if not item.get("why"):
        raise StackError(f"{where}: why 가 없다 — {item['id']}. 근거 없는 항목은 취향이다")


def load() -> tuple[dict[str, dict], dict[str, dict]]:
    """(스택, 프리셋). 어긋난 정의는 여기서 전부 실패시킨다."""
    stacks: dict[str, dict] = {}
    seen_ids: dict[str, str] = {}

    for path in sorted(STACKS.glob("*.yaml")):
        if path.name == "presets.yaml":
            continue
        data = _read(path)
        name = data.get("name")
        if not name:
            raise StackError(f"{path.name}: name 이 없다")
        blocks = [("base", {"items": data.get("base") or []})]
        optional = data.get("optional") or {}
        blocks += [(f"optional.{k}", v or {}) for k, v in optional.items()]
        strippable = data.get("strippable") or {}
        for where, block in blocks:
            # 오타난 strips 키는 조용히 아무것도 지우지 않는다 — ESLint 가 Biome 옆에
            # 그대로 남는다. 다른 어긋남과 같은 자리(로드 시점)에서 잡는다.
            for sid in block.get("strips") or []:
                if sid not in strippable:
                    raise StackError(
                        f"{path.name}:{where}: strips 의 {sid!r} 를 strippable 에서 못 찾았다"
                    )
            for item in _items_of(block):
                _validate_item(item, f"{path.name}:{where}")
                # 같은 도구가 두 곳에 정의되면 한쪽만 고치는 사고가 난다 — 정의는 한 곳에만.
                if item["id"] in seen_ids and seen_ids[item["id"]] != f"{name}:{where}":
                    raise StackError(
                        f"id {item['id']!r} 가 두 곳에 정의됐다: "
                        f"{seen_ids[item['id']]} / {name}:{where}"
                    )
                seen_ids[item["id"]] = f"{name}:{where}"
        stacks[name] = data

    presets = _read(STACKS / "presets.yaml").get("presets") or {}
    aliases: dict[str, str] = {}
    for pname, p in presets.items():
        lang = p.get("lang")
        if lang not in stacks:
            raise StackError(f"프리셋 {pname}: 모르는 lang {lang!r}")
        for key in p.get("with") or []:
            if _find_optional(stacks, lang, key) is None:
                raise StackError(f"프리셋 {pname}: {lang} 도 common 도 {key!r} 를 모른다")
        for alias in [pname] + list(p.get("aliases") or []):
            if alias in aliases and aliases[alias] != pname:
                # 조용히 하나를 고르면 같은 말이 다른 조합으로 간다.
                raise StackError(f"alias {alias!r} 를 {aliases[alias]} 와 {pname} 가 함께 주장한다")
            aliases[alias] = pname
    return stacks, presets


def catalog_items() -> dict[str, dict]:
    """카탈로그 전체의 id → 항목. id 는 전역 유일임을 load() 가 보장한다.

    "이 분기가 아직 카탈로그에 있는가" 를 판정하는 근거다 — 프로젝트별 적용 기록 없이
    **다른 스택이 쓰는 분기**(유지)와 **은퇴한 항목**(제거)을 가른다.
    """
    all_stacks, _ = load()
    out: dict[str, dict] = {}
    for stack in all_stacks.values():
        blocks = [{"items": stack.get("base") or []}]
        blocks += [b or {} for b in (stack.get("optional") or {}).values()]
        for block in blocks:
            for item in _items_of(block):
                out[item["id"]] = item
    return out


def _find_optional(stacks: dict, lang: str, key: str) -> dict | None:
    """optional 키는 그 언어에서 찾고, 없으면 common 에서 찾는다."""
    for owner in (lang, "common"):
        block = ((stacks.get(owner) or {}).get("optional") or {}).get(key)
        if block is not None:
            return block or {}
    return None


def alias_map(presets: dict) -> dict[str, str]:
    out = {}
    for pname, p in presets.items():
        for alias in [pname] + list(p.get("aliases") or []):
            out[alias] = pname
    return out


