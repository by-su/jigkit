def plan(combo: dict, target: Path) -> list[tuple[str, str]]:
    """실행할 셸 명령 목록. 스킬이 이것을 순서대로 돌린다 — 인자를 창작하지 않는다.

    **각 줄은 그 자체로 완결이다.** 예전에는 `cd <경로>` 를 한 줄로 내고 나머지가 그 셸을
    물려받는다고 가정했는데, 이 하네스의 에이전트는 Bash 호출마다 cwd 가 초기화된다 —
    그러면 install 이 엉뚱한 디렉터리로 간다. 그래서 프로젝트 안에서 돌아야 하는 줄은
    전부 `cd <경로> && …` 로 스스로를 고정한다.
    """
    steps: list[tuple[str, str]] = []
    if target.exists() and not target.is_dir():
        raise StackError(f"{target} 는 디렉터리가 아니다")
    empty = not target.exists() or not any(target.iterdir())
    created = bool(combo["create"]) and empty
    # 스킬은 이 줄을 **그대로** 실행한다. 공백이 든 경로(`~/My Projects/api`)를 안 감싸면
    # 모든 단계가 엉뚱한 디렉터리에서 돌거나 실패한다.
    q, qparent, qname = (shlex.quote(str(target)), shlex.quote(str(target.parent)),
                         shlex.quote(target.name))

    def inproj(cmd: str) -> str:
        return f"cd {q} && {cmd}"

    if created:
        # 경로를 못 다루는 스캐폴더가 있다 — nest 는 절대경로를 소문자로 낮추거나 상대경로로
        # 취급한다 [M]. 그런 경우 부모에서 이름만 주고 돌리므로 세 형태를 다 준다.
        steps.append(("create", combo["create"]
                      .replace("{dir}", q)
                      .replace("{parent}", qparent)
                      .replace("{name}", qname)))

    # strips 는 **스캐폴더가 방금 깐 것**을 지우는 단계다. create 를 건너뛴 기존 프로젝트에
    # 내면 `pnpm remove` 가 없는 의존성에 에러를 내며 계획이 중간에 죽는다 [M].
    if created:
        for sid in combo["strips"]:
            entry = combo["strippable"].get(sid) or {}
            if entry.get("remove"):
                steps.append(("strip", inproj(entry["remove"])))
            for f in entry.get("files") or []:
                steps.append(("strip", inproj(f"rm -f {f}")))

    for item in combo["items"]:
        if item.get("install"):
            steps.append(("install", inproj(item["install"])))
    for item in combo["items"]:
        if item.get("init"):
            steps.append(("init", inproj(item["init"])))

    # 선택 키를 그대로 다시 넘긴다 — 프리셋이 이미 포함하는 키여도 해석은 멱등이다.
    # 이 줄은 경로를 인자로 받으므로 cd 가 필요 없다.
    args = combo["spec"]
    if combo["keys"]:
        args += " --with " + ",".join(combo["keys"])
    steps.append(("apply", f"jig stack apply {args} {q} --apply"))

    # 스캐폴더·init 이 만든 파일을 우리 규칙으로 정리한다. **apply 뒤에 와야 한다** —
    # 설정 파일(biome.json 등)을 apply 가 배치하므로, 앞에 두면 도구 기본값으로 포맷한 뒤
    # 규칙이 바뀌어 verify 가 전부 실패한다 [M] (probe/results/stack-scaffold.md).
    if combo.get("normalize"):
        steps.append(("normalize", inproj(combo["normalize"])))

    for v in combo["verify"]:
        steps.append(("verify", inproj(v)))
    return steps


# ----------------------------------------------------------------------- check

def _pep508_name(spec: str) -> str:
    """`fastapi[standard]>=0.1` -> `fastapi`."""
    name = spec.strip()
    for sep in ("[", ">", "<", "=", "!", "~", ";", " ", "@"):
        name = name.split(sep)[0]
    return name.strip().lower()


def _deps(project: Path) -> set[str]:
    """선언된 의존성 이름. 잠금파일이 아니라 선언을 본다 — 사람이 고치는 쪽이다.

    선언 섹션만 파싱한다. 파일 전체에서 따옴표 문자열을 긁으면 `name = "x"` 같은 것까지
    의존성으로 세고, **없는 것을 있다고 말하는** 쪽으로 틀린다 — check 에서 가장 나쁜 방향이다.
    """
    names: set[str] = set()

    pkg = project / "package.json"
    if pkg.is_file():
        try:
            data = json.loads(pkg.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            data = {}
        if not isinstance(data, dict):     # 최상위가 배열인 package.json 도 파싱은 된다
            data = {}
        for key in ("dependencies", "devDependencies", "peerDependencies"):
            names |= {k.lower() for k in (data.get(key) or {})}

    pyproject = project / "pyproject.toml"
    if pyproject.is_file():
        try:
            data = tomllib.loads(pyproject.read_text(encoding="utf-8"))
        except tomllib.TOMLDecodeError:
            data = {}
        buckets: list[list] = [(data.get("project") or {}).get("dependencies") or []]
        buckets += list(((data.get("project") or {}).get("optional-dependencies") or {}).values())
        buckets += list((data.get("dependency-groups") or {}).values())          # PEP 735 (uv)
        buckets.append(((data.get("tool") or {}).get("uv") or {}).get("dev-dependencies") or [])
        for bucket in buckets:
            names |= {_pep508_name(s) for s in bucket if isinstance(s, str)}
    return names


def _detected(spec: dict, project: Path, deps: set[str]) -> bool:
    if "dep" in spec:
        return str(spec["dep"]).lower() in deps
    if "file" in spec:
        return (project / spec["file"]).exists()
    if "mcp" in spec:
        return (MCP_DIR / f"{spec['mcp']}.json").is_file()
    return False


def active_ids(text: str) -> set[str]:
    """디스패처의 **생성물 구간 안에서 살아 있는** 분기 id.

    파일 전체를 문자열로 훑으면 사람이 주석 처리한 분기도 "있다" 고 세어 버린다 —
    체크의 false negative 는 이 장치에서 가장 나쁜 고장이므로 구간과 활성 여부를 본다.
    """
    if HOOK_MARKERS[0] not in text:
        return set()
    inside = text.split(HOOK_MARKERS[0], 1)[1].split(HOOK_MARKERS[1], 1)[0]
    found = set()
    for line in inside.splitlines():
        if not line.strip() or line.strip().startswith("#"):
            continue
        if m := ID_COMMENT.search(line):
            found.add(m.group(1))
    return found


def undetected(combo: dict, project: Path) -> list[str]:
    """조합 중 **프로젝트에 실제로 깔려 있지 않은** 항목. 표면이 배치됐는지는 보지 않는다.

    `apply` 는 훅·게이트를 배선할 뿐 도구를 깔지 않는다. 도구 없이 배선만 끝나면 증상은
    매 편집마다 나오는 stderr 뿐이라 아무도 눈치채지 못한다 — `check` 를 따로 부르지
    않는 사람에게도 그 자리에서 말해야 한다.
    """
    if not project.exists():
        return []
    deps = _deps(project)
    return [i["id"] for i in combo["items"]
            if i.get("detect") and not _detected(i["detect"], project, deps)]


def check(combo: dict, project: Path) -> list[tuple[str, str]]:
    """선언 ↔ 실제. 빠진 것과 충돌을 돌려준다. 빈 목록이면 조합대로 배치돼 있다."""
    if not project.exists():
        return [("(프로젝트)", f"{project} 가 없다")]

    deps = _deps(project)
    missing: list[tuple[str, str]] = []

    def ids_in(rel: str) -> set[str]:
        path = project / ".claude" / "hooks" / rel
        return active_ids(path.read_text(encoding="utf-8")) if path.is_file() else set()

    fmt_ids, gate_ids = ids_in("jig-format"), ids_in("jig-gate")

    for item in combo["items"]:
        iid, surface = item["id"], item["surface"]
        flagged = False
        if surface == "hook" and iid not in fmt_ids:
            missing.append((iid, "포맷 디스패처에 살아 있는 분기가 없다 — jig stack apply"))
            flagged = True
        elif surface == "gate" and iid not in gate_ids:
            missing.append((iid, "게이트 디스패처에 살아 있는 분기가 없다 — jig stack apply"))
            flagged = True
        elif surface == "mcp" and not (MCP_DIR / f"{iid}.json").is_file():
            missing.append((iid, f"library/mcp/{iid}.json 이 없다 — jig stack apply"))
            flagged = True

        # 표면 검사를 통과했어도 **도구가 깔렸는지는 따로 본다.** 예전에는 hook·gate·mcp 가
        # 표면 검사 뒤에 그대로 빠져나가서, 훅은 걸렸는데 ruff·pyright 가 안 깔린 프로젝트를
        # check 가 "ok" 라고 했다 — 매 편집마다 stderr 만 나오고 아무도 눈치채지 못하는,
        # 이 장치에서 가장 나쁜 방향의 고장이다.
        if not flagged and item.get("detect") and not _detected(item["detect"], project, deps):
            missing.append((iid, f"감지 실패: {item['detect']}"))

    # 빠진 것만 보면 반쪽이다 — **카탈로그에서 은퇴한 항목의 분기가 남아 계속 도는** 쪽도
    # 봐야 한다. 다른 스택이 쓰는 분기(카탈로그에 있고 표면이 맞는 것)는 정상이므로 뺀다.
    catalog = catalog_items()
    for rel, found, surface in (("jig-format", fmt_ids, "hook"),
                                ("jig-gate", gate_ids, "gate")):
        for iid in sorted(found):
            item = catalog.get(iid)
            if item is None or item["surface"] != surface:
                missing.append((iid, f".claude/hooks/{rel} 에 남아 있지만 카탈로그에 없다 "
                                     f"— jig stack apply 가 은퇴시킨다"))

    ours = {i["id"] for i in combo["items"]}
    for mine, theirs in combo["conflicts"]:
        if mine not in ours:
            continue
        spec = (combo["strippable"].get(theirs) or {}).get("detect") or {"dep": theirs}
        if _detected(spec, project, deps):
            missing.append((theirs, f"{mine} 와 충돌하는데 프로젝트에 남아 있다"))
    return missing


