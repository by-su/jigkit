def _row(item: dict) -> str:
    why = str(item.get("why", "")).replace("|", "\\|")
    return f"| {item['role']} | `{item['id']}` | {item['surface']} | {why} |"


def _by_role(items: list[dict]) -> list[dict]:
    return sorted(items, key=lambda i: (ROLES.index(i["role"]), i["id"]))


def render_catalog() -> str:
    """`library/stacks/README.md` 의 카탈로그 블록. 언어별 → 기능별."""
    stacks, presets = load()
    out: list[str] = []

    for name in sorted(stacks):
        stack = stacks[name]
        out += ["", f"### {stack.get('title', name)} (`{name}`)", ""]
        base = _by_role(stack.get("base") or [])
        if base:
            out += ["**base** — 이 언어면 항상 들어간다", "",
                    "| 기능 | 도구 | 표면 | 근거 |", "|---|---|---|---|"]
            out += [_row(i) for i in base]
            out += [""]
        optional = stack.get("optional") or {}
        if optional:
            out += ["**optional** — `--with` 나 프리셋으로 고른다", "",
                    "| 키 | 기능 | 도구 | 표면 | 근거 |", "|---|---|---|---|---|"]
            for key in sorted(optional):
                for item in _by_role(_items_of(optional[key] or {})):
                    out.append(f"| `{key}` " + _row(item))
            out += [""]

    out += ["### 프리셋", "", "| 이름 | 언어 | 포함 | 이렇게 부르면 걸린다 |", "|---|---|---|---|"]
    for pname in sorted(presets):
        p = presets[pname]
        with_ = ", ".join(f"`{k}`" for k in p.get("with") or []) or "—"
        aliases = ", ".join(f"`{a}`" for a in p.get("aliases") or []) or "—"
        out.append(f"| **{pname}** | {p['lang']} | {with_} | {aliases} |")
    return "\n".join(out[1:] if out and out[0] == "" else out)


def list_lines() -> list[str]:
    stacks, presets = load()
    out = ["프리셋 — 이 이름이나 alias 로 부른다"]
    for pname in sorted(presets):
        p = presets[pname]
        out.append(f"  {pname:<10} {p['lang']:<11} {p.get('title', '')}")
        out.append(f"  {'':<10} + {', '.join(p.get('with') or []) or '(base 만)'}")
        out.append(f"  {'':<10} = {', '.join(p.get('aliases') or [])}")
    out += ["", "언어 스택 — 직접 부를 수도 있다"]
    for name in sorted(stacks):
        stack = stacks[name]
        nbase = len(stack.get("base") or [])
        keys = sorted((stack.get("optional") or {}))
        out.append(f"  {name:<11} base {nbase}개  optional: {', '.join(keys) or '없음'}")
    return out


def show_lines(combo: dict) -> list[str]:
    out = [f"{combo['label']} — {combo['title']}"]
    if combo["keys"]:
        out.append(f"  선택: {', '.join(combo['keys'])}")
    if combo["create"]:
        out.append(f"  스캐폴드: {combo['create']}")
    if combo["strips"]:
        out.append(f"  제거: {', '.join(combo['strips'])}")
    out.append("")

    for surface in SURFACES:
        mine = [i for i in _by_role(combo["items"]) if i["surface"] == surface]
        if not mine:
            continue
        note = {
            "hook": "  → 항목 하나(.claude/hooks/jig-format)의 분기로 들어간다",
            "gate": "  → 항목 하나(.claude/hooks/jig-gate)의 분기로 들어간다",
            "mcp": "  → library/mcp/<id>.json 만 만든다. 프로필에 켜는 것은 사람이 한다",
            "agents": "  → init 이 대상 프로젝트에 에이전트 정의를 만든다",
            "library": "  → 설치만. 에이전트 표면이 없다",
        }[surface]
        out.append(f"{surface}{note}")
        for item in mine:
            out.append(f"    {item['role']:<14} {item['id']}")
        out.append("")
    if combo["verify"]:
        out.append("verify")
        out += [f"    {v}" for v in combo["verify"]]
    return out
