def resolve(spec: str, with_keys: list[str] | None = None) -> dict:
    """언어 이름 · 프리셋 이름 · alias 를 조합으로 펼친다.

    반환에는 배치될 항목(items)과 그 조합의 create·strips·verify·conflicts 가 들어간다.
    """
    stacks, presets = load()
    extra = list(with_keys or [])

    pname = alias_map(presets).get(spec)
    if pname:
        preset = presets[pname]
        lang, keys, title = preset["lang"], list(preset.get("with") or []), preset.get("title", pname)
        label = f"{pname} ({lang})"
    elif spec in stacks:
        lang, keys, title = spec, [], stacks[spec].get("title", spec)
        label = spec
    else:
        known = sorted(set(list(stacks) + list(alias_map(presets))))
        raise StackError(f"모르는 스택·프리셋 {spec!r}. 아는 것: {', '.join(known)}")

    for k in extra:
        if k not in keys:
            keys.append(k)

    # requires 를 **바뀌지 않을 때까지** 닫는다. 반복 횟수를 처음 키 개수로 묶으면 사슬이
    # 깊을 때 조용히 덜 닫힌다 — 오류 없이 항목 하나가 빠지는 형태다.
    grew = True
    while grew:
        grew = False
        for k in list(keys):
            block = _find_optional(stacks, lang, k)
            if block is None:
                raise StackError(f"{lang} 도 common 도 {k!r} 를 모른다")
            for dep in block.get("requires") or []:
                if dep not in keys:
                    keys.append(dep)
                    grew = True

    stack = stacks[lang]
    items: list[dict] = []
    creates: list[tuple[str, str]] = []
    strips: list[str] = []
    verify: list[str] = list(stack.get("verify") or [])

    def add(item: dict) -> None:
        if not any(i["id"] == item["id"] for i in items):
            items.append(item)

    for item in stack.get("base") or []:
        add(item)
    if stack.get("create"):
        creates.append((lang, stack["create"]))

    for k in keys:
        block = _find_optional(stacks, lang, k) or {}
        for item in _items_of(block):
            add(item)
        if block.get("create"):
            creates.append((k, block["create"]))
        strips += [s for s in (block.get("strips") or []) if s not in strips]
        verify += [v for v in (block.get("verify") or []) if v not in verify]

    # 스캐폴더가 둘이면 어느 쪽이 프로젝트를 만드는지 알 수 없다.
    scaffolds = [c for c in creates if c[0] != lang]
    if len(scaffolds) > 1:
        raise StackError(
            "스캐폴더가 둘이다: " + ", ".join(k for k, _ in scaffolds) +
            " — 한 번에 하나만 고른다"
        )
    create = (scaffolds or creates or [(None, None)])[0][1]

    # 같은 role 에 게이트가 둘이면 서로 다른 규칙으로 같은 파일을 판정한다.
    gates: dict[str, str] = {}
    for item in items:
        if item["surface"] == "gate":
            if item["role"] in gates:
                raise StackError(
                    f"role {item['role']!r} 에 게이트가 둘이다: "
                    f"{gates[item['role']]} / {item['id']} — 하나만 남긴다"
                )
            gates[item["role"]] = item["id"]

    conflicts = [tuple(c) for c in (stack.get("conflicts") or [])]
    conflicts += [tuple(c) for c in ((stacks.get("common") or {}).get("conflicts") or [])]

    return {
        "spec": spec, "label": label, "title": title, "lang": lang, "keys": keys,
        "items": items, "create": create, "strips": strips, "verify": verify,
        "normalize": stack.get("normalize"), "conflicts": conflicts,
        "strippable": stack.get("strippable") or {},
    }


